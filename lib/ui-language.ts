function translateDynamicText(value: string) {
  const patterns: Array<[RegExp, (...parts: string[]) => string]> = [
    [/^(\d{4}) workplan$/, (year) => `${year} оны ажлын төлөвлөгөө`],
    [/^Create (\d{4}) workplan$/, (year) => `${year} оны ажлын төлөвлөгөө үүсгэх`],
    [/^Remove the (\d{4}) workplan\?$/, (year) => `${year} оны ажлын төлөвлөгөөг устгах уу?`],
    [/^Remove (\d{4}) workplan$/, (year) => `${year} оны ажлын төлөвлөгөөг устгах`],
    [/^(\d{4}) workplan removed$/, (year) => `${year} оны ажлын төлөвлөгөөг устгалаа`],
    [/^(\d+) activities$/, (count) => `${count} арга хэмжээ`],
    [/^(\d+) entries$/, (count) => `${count} бичилт`],
    [/^(\d+) of (\d+) entries$/, (shown, total) => `${total}-аас ${shown} бичилт`],
    [/^Sub-activity (\d+)$/, (index) => `Дэд ажил ${index}`],
    [/^Owner (\d+)$/, (index) => `Хариуцагч ${index}`],
    [/^Optional owner (\d+)$/, (index) => `Нэмэлт хариуцагч ${index}`],
    [/^Supporting owner (\d+)$/, (index) => `Дэмжих хариуцагч ${index}`],
    [/^Supporting: (.+)$/, (names) => `Дэмжих: ${names}`],
    [/^\+ (\d+) supporting$/, (count) => `+ ${count} дэмжих`],
    [/^Last saved (.+)$/, (date) => `Сүүлд хадгалсан: ${date}`],
    [/^(\d+)% · calculated$/, (percent) => `${percent}% · автоматаар тооцоолсон`],
    [/^(\d+) assigned$/, (count) => `${count} хариуцуулсан`],
    [/^(\d+) selected$/, (count) => `${count} сонгосон`],
    [/^(\d+) contracts linked to the selected workplan scope\.$/, (count) => `Сонгосон хамрах хүрээнд ${count} гэрээ байна.`],
    [/^(\d+) main activities, (\d+) sub-activities, and (\d+) open contracts were carried forward\.$/, (activities, subactivities, contracts) => `${activities} үндсэн арга хэмжээ, ${subactivities} дэд ажил, ${contracts} нээлттэй гэрээг дараа жилд шилжүүллээ.`],
    [/^Entered by (.+)$/, (name) => `Оруулсан: ${name}`],
    [/^Section ([AB])$/, (section) => `${section} хэсэг`],
  ];
  for (const [pattern, formatter] of patterns) {
    const match = value.match(pattern);
    if (match) return formatter(...match.slice(1));
  }
  return value;
}

export function translateUiText(value: string, language: UiLanguage) {
  if (language === "en") return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  const translated = mn[core] ?? translateDynamicText(core);
  return `${leading}${translated}${trailing}`;
}
